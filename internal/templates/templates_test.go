// TestProjectWorkingDir: the project is mounted at working_dir (default /app), the container starts
// there, and the webserver root and PHP_IDE_CONFIG follow the project's settings.
func TestProjectWorkingDir(t *testing.T) {
	for _, c := range []struct{ dir, ide, wantDir, wantIDE string }{
		{"", "", "/app", "serverName=shop"},
		{"/var/www/html", "shop-ide", "/var/www/html", "serverName=shop-ide"},
	} {
		in := projectInput("nginx")
		p := *in.Project
		p.WorkingDir, p.PHPIDEConfig = c.dir, c.ide
		in.Project = &p
		web := parse(t, must(t)(ProjectCompose(in)))["web"]
		if web.WorkingDir != c.wantDir || !slices.Contains(web.Volumes, p.Root+":"+c.wantDir) {
			t.Errorf("%q: working_dir %q, volumes %v", c.dir, web.WorkingDir, web.Volumes)
		}
		for _, e := range []string{"LODEV_WORKDIR=" + c.wantDir, "PHP_IDE_CONFIG=" + c.wantIDE} {
			if !slices.Contains(web.Environment, e) {
				t.Errorf("%q: missing %s in %v", c.dir, e, web.Environment)
			}
		}
		conf := string(must(t)(WebserverConfig(&p)))
		for _, w := range []string{"set $MAGE_ROOT " + c.wantDir + ";", "root " + c.wantDir + "/pub;"} {
			if !strings.Contains(conf, w) {
				t.Errorf("%q: webserver config lacks %q", c.dir, w)
			}
		}
	}
}
