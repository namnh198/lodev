func currentProject() (*config.Project, error) {
	wd, err := os.Getwd()
	if err != nil {
		return nil, err
	}
	root, err := config.FindRoot(wd)
	if err != nil {
		return nil, err
	}
	return config.LoadProject(root)
}

// projectArg is the project named in args (looked up in the registry), or the current folder's.
func projectArg(args []string) (*config.Project, error) {
	if len(args) == 0 {
		return currentProject()
	}
	reg, err := registry.Load()
	if err != nil {
		return nil, err
	}
	e, ok := reg[args[0]]
	if !ok {
		return nil, fmt.Errorf("unknown project %q (see: lodev list)", args[0])
	}
	return config.LoadProject(e.Path)
}

// existingProject is projectArg for start and restart: the project must have a .lodev/config.yaml
// and be registered with lodev (lodev create does both). It is looked up by folder, so a project
// renamed in its config.yaml still starts (and retires its old name).
func existingProject(args []string) (*config.Project, error) {
	if len(args) > 0 {
		return projectArg(args)
	}
	wd, err := os.Getwd()
	if err != nil {
		return nil, err
	}
	root, err := config.FindRoot(wd)
	if err != nil {
		return nil, errors.New("project does not exist: no .lodev/config.yaml in this folder or above (run lodev create)")
	}
	reg, err := registry.Load()
	if err != nil {
		return nil, err
	}
	if !registered(reg, root) {
		return nil, fmt.Errorf("project does not exist: %s is not registered with lodev (run lodev create)", root)
	}
	return config.LoadProject(root)
}

func registered(reg registry.Registry, root string) bool {
	for _, e := range reg {
		if e.Path == root {
			return true
		}
	}
	return false
}

// registerProject adds p to the registry, refusing a name or domain another project uses.
func registerProject(p *config.Project) error {
	reg, err := registry.Load()
	if err != nil {
		return err
	}
	if err := reg.Conflict(p); err != nil {
		return err
	}
	reg.Put(p)
	return reg.Save()
}

// WebserverConfFile is the generated webserver config, mounted into the container.
func WebserverConfFile(p *config.Project) string {
	return filepath.Join(p.Root, ".lodev", p.Webserver+"-webserver.conf")
}

func composeBase(p *config.Project) string {
	return filepath.Join(p.Root, ".lodev", "lodev.compose-base.yml")
}

func composeFull(p *config.Project) string {
	return filepath.Join(p.Root, ".lodev", "lodev.compose-full.yml")
}

// composeFile is the merged file every compose call uses.
// Projects last started by an older lodev only have the legacy file.
func composeFile(p *config.Project) string {
	full := composeFull(p)
	if _, err := os.Stat(full); err != nil {
		if _, lerr := os.Stat(composeLegacy(p)); lerr == nil {
			return composeLegacy(p)
		}
	}
	return full
}
func composeLegacy(p *config.Project) string  { return filepath.Join(p.Root, ".lodev", "compose.yaml") }
func composeProject(p *config.Project) string { return "lodev-" + p.Name }

var composeConfig = func(args ...string) (string, error) { return docker.Output(args...) }

// extraComposeFiles lists the user's dir/*.compose.{yml,yaml}, sorted.
func extraComposeFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return nil, err
	}
	var files []string
	for _, e := range entries { // ReadDir is sorted by name
		n := e.Name()
		if e.Type().IsRegular() && (strings.HasSuffix(n, ".compose.yml") || strings.HasSuffix(n, ".compose.yaml")) {
			files = append(files, filepath.Join(dir, n))
		}
	}
	return files, nil
}

// mergeComposeFiles writes full only if `docker compose config` over base+extra succeeds.
func mergeComposeFiles(project, base, full string, extra []string) error {
	out, err := composeConfig(docker.ComposeConfigArgs(project, append([]string{base}, extra...))...)
	if err != nil {
		return err
	}
	// compose config drops comments: put the header back.
	header := "# generated by lodev. Do NOT change anything\n# Merged from " + filepath.Base(base) +
		" and the *.compose.yml files here: edit those instead.\n"
	return os.WriteFile(full, []byte(header+out+"\n"), 0o644)
}

func mergeCompose(p *config.Project) error {
	extra, err := extraComposeFiles(filepath.Join(p.Root, ".lodev"))
	if err != nil {
		return err
	}
	return mergeComposeFiles(composeProject(p), composeBase(p), composeFull(p), extra)
}

var dockerOutput = docker.Output

// removeProjectImage drops the built web image; a project that never built one has none.
func removeProjectImage(name string) error {
	if _, err := dockerOutput("rmi", config.ProjectImage(name)); err != nil && !strings.Contains(err.Error(), "No such image") {
		return err
	}
	return nil
}

// dropStaleProjectImage removes a no-longer-needed project image once compose
// runs the container on img; it is a no-op while img is still the project image.
func dropStaleProjectImage(p *config.Project, img string) error {
	if img == config.ProjectImage(p.Name) {
		return nil
	}
	return removeProjectImage(p.Name)
}

func userWarning(name, from string) string {
	if from == "" {
		return ""
	}
	return fmt.Sprintf("%q is not a valid container user name; using %q (set user: in .lodev/config.yaml to choose another)", from, name)
}

var userPoll = time.Second

// userReady reports whether the entrypoint has created user in the web container.
var userReady = func(p *config.Project, user string) bool {
	_, err := docker.Output(docker.ExecArgs(composeProject(p), composeFile(p), "web", "", "", false, []string{"id", "-u", user})...)
	return err == nil
}

// waitForUser blocks until the entrypoint has created user, so ssh/exec right after start work.
func waitForUser(p *config.Project, user string, timeout time.Duration) error {
	for deadline := time.Now().Add(timeout); ; time.Sleep(userPoll) {
		if userReady(p, user) {
			return nil
		}
		if time.Now().After(deadline) {
			return fmt.Errorf("user %q was not created in the web container; check: docker logs lodev-%s-web", user, p.Name)
		}
	}
}

func projectCompose(p *config.Project, sub ...string) error {
	return dockerRun(docker.ComposeArgs(composeProject(p), composeFile(p), sub...)...)
}

// dbExec runs sql as root in the shared database db ("mysql" or "mariadb"; MariaDB 11 has no mysql client).
func dbExec(db, sql string) error {
	_, err := dockerOutput("exec", "lodev-"+db, db, "-uroot", "-proot", "-e", sql)
	return err
}

// newProjectConfig fills unset values from what is detected in root.
func newProjectConfig(root, name, typ, php, webserver, docroot string) (*config.Project, error) {
	if name == "" {
		if name = config.SanitizeName(filepath.Base(root)); name == "" {
			return nil, fmt.Errorf("cannot derive a project name from folder %q; use --name", filepath.Base(root))
		}
	}
	if typ == "" {
		typ = config.DetectType(root)
	}
	if php == "" {
		php = "8.4"
	}
	switch docroot {
	case "":
		docroot = config.DefaultDocroot(typ)
	case ".":
		docroot = ""
	}
	p := &config.Project{
		Name: name, Type: typ, PHP: php, Webserver: webserver,
		Docroot: docroot, Services: defaultServices[typ], Root: root,
	}
	p.ApplyDefaults()
	return p, p.Validate()
}

// generated reports whether path is missing or still carries the lodev marker as its first line.
func generated(path string) bool {
	b, err := os.ReadFile(path)
	if err != nil {
		return errors.Is(err, os.ErrNotExist)
	}
	first, _, _ := strings.Cut(string(b), "\n")
	return first == templates.GeneratedMarker
}

func writeWebserverConf(p *config.Project) error {
	if p.Webserver == "none" {
		return nil
	}
	path := WebserverConfFile(p)
	if !generated(path) {
		ui.Info(".lodev/%s-webserver.conf is user-managed; not regenerating", p.Webserver)
		return nil
	}
	conf, err := templates.WebserverConfig(p)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, conf, 0o644)
}

func varnishVCLFile(p *config.Project) string { return filepath.Join(p.Root, ".lodev", "varnish.vcl") }

// writeVarnishVCL writes the default VCL while Varnish is on and lodev still owns the file.
func writeVarnishVCL(p *config.Project) error {
	if !p.Varnish {
		return nil
	}
	path := varnishVCLFile(p)
	if !generated(path) {
		ui.Info(".lodev/varnish.vcl is user-managed; not regenerating")
		return nil
	}
	vcl, err := templates.VarnishVCL(p)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, vcl, 0o644)
}

// writeLodevGitignore ignores generated files; a webserver conf is listed only while lodev owns it.
func writeLodevGitignore(p *config.Project) error {
	dir := filepath.Join(p.Root, ".lodev")
	s := "# Generated by lodev on every `lodev start`; do not edit.\n/lodev.compose-base.yml\n/lodev.compose-full.yml\n/web-build/\n/crontab\n/.env\n" +
		"# each <ws>-webserver.conf below is listed only while it carries the marker\n"
	for _, ws := range []string{"nginx", "apache"} {
		if generated(filepath.Join(dir, ws+"-webserver.conf")) {
			s += "/" + ws + "-webserver.conf\n"
		}
	}
	if generated(varnishVCLFile(p)) {
		s += "/varnish.vcl\n"
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, ".gitignore"), []byte(s), 0o644)
}

var (
	containerRunning = docker.Running
	servicesUpFn     = servicesUp
)

// ensureServices brings the shared services up unless traefik, every enabled service and every
// service p needs already run; `lodev service start` is the way to apply config changes to them.
func ensureServices(p *config.Project) error {
	g, err := config.LoadGlobal()
	if err != nil {
		return err
	}
	needed := append(append([]string{"traefik"}, g.EnabledServices()...), p.Services...)
	if !slices.ContainsFunc(needed, func(svc string) bool { return !containerRunning("lodev-" + svc) }) {
		return nil
	}
	if err := servicesUpFn(); err != nil {
		return err
	}
	for _, svc := range p.Services {
		if !g.Services[svc] {
			if err := startService(svc); err != nil {
				return err
			}
			ui.Info("hint: %s is disabled globally; started it for now. Run `lodev service enable %s` to keep it on.", svc, svc)
		}
	}
	return nil
}

// startOpts picks the images start rebuilds without the layer cache, and whether hooks run.
type startOpts struct{ project, base, noHooks bool }

func start(p *config.Project, rebuild startOpts) error {
	user, from := p.ContainerUser()
	if w := userWarning(user, from); w != "" {
		ui.Warn("%s", w)
	}
	reg, err := registry.Load()
	if err != nil {
		return err
	}
	if err := reg.Conflict(p); err != nil {
		return err
	}
	if err := ensureServices(p); err != nil {
		return err
	}
	g, err := config.LoadGlobal()
	if err != nil {
		return err
	}
	if err := docker.EnsurePHPImage(p.PHP, g.NodeVersion, rebuild.base); err != nil {
		return err
	}
	img, err := docker.EnsureProjectImage(p, rebuild.project)
	if err != nil {
		return err
	}
	if db := p.DB(); db != "" {
		if err := waitDB(db, g); err != nil {
			return err
		}
		if err := dbExec(db, fmt.Sprintf("CREATE DATABASE IF NOT EXISTS `%s`", p.DBName())); err != nil {
			return err
		}
	}
	if p.Webserver != "none" {
		if err := certs.Ensure(p.Name, p.Domains); err != nil {
			return err
		}
		if err := certs.SyncTraefik(); err != nil {
			return err
		}
		if err := writeWebserverConf(p); err != nil {
			return err
		}
		if err := writeVarnishVCL(p); err != nil {
			return err
		}
		legacy := filepath.Join(p.Root, ".lodev", "webserver.conf")
		if err := os.Remove(legacy); err != nil && !errors.Is(err, os.ErrNotExist) {
			return err
		}
	}
	// Also creates the bind-mounted php/ and <webserver>/ dirs, and brings projects made before them up to date.
	if err := scaffold(p.Root, p.Webserver); err != nil {
		return err
	}
	if err := writeLodevGitignore(p); err != nil {
		return err
	}
	// WebDomains is nil for CLI projects, which also clears a block left from an earlier webserver.
	if err := hosts.Apply(p.Name, p.WebDomains()); err != nil {
		return err
	}
	dropped := reg.Put(p)
	for _, old := range dropped {
		// Renamed project: retire the old name's container, hosts block and cert (its database is kept).
		ui.Info("Project was renamed from %s; removing its old container, hosts entries and certificate.", old)
		if err := docker.Run("compose", "-p", "lodev-"+old, "down"); err != nil {
			return err
		}
		if err := removeProjectImage(old); err != nil {
			return err
		}
		if err := hosts.Apply(old, nil); err != nil {
			return err
		}
		if err := certs.Remove(old); err != nil {
			return err
		}
	}
	if len(dropped) > 0 {
		if err := certs.SyncTraefik(); err != nil {
			return err
		}
	}
	if err := reg.Save(); err != nil {
		return err
	}
	// The web container mounts the CA: a missing one would become a root-owned folder.
	if err := certs.EnsureCA(); err != nil {
		return err
	}
	ca, err := certs.CAFile()
	if err != nil {
		return err
	}
	env, err := projectEnv(p)
	if err != nil {
		return err
	}
	if err := writeCrontab(p); err != nil {
		return err
	}
	// Created here, not by Docker: Docker would create a missing bind source owned by root.
	home := projectHome(g, p)
	if err := os.MkdirAll(home, 0o755); err != nil {
		return err
	}
	data, err := templates.ProjectCompose(templates.ProjectInput{
		Project:    p,
		ExtraHosts: reg.AllDomains(),
		CAFile:     ca,
		Image:      img,
		User:       user,
		UID:        os.Getuid(),
		GID:        os.Getgid(),
		HomeDir:    home,
		Env:        env,
	})
	if err != nil {
		return err
	}
	if err := os.WriteFile(composeBase(p), data, 0o644); err != nil {
		return err
	}
	if err := mergeCompose(p); err != nil {
		return err
	}
	if err := os.Remove(composeLegacy(p)); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	warnWorkDirMove(p)
	if err := projectCompose(p, "up", "-d", "--remove-orphans"); err != nil {
		return err
	}
	if err := waitWeb(p, g); err != nil {
		return err
	}
	if err := waitForUser(p, user, 10*time.Second); err != nil {
		return err
	}
	syncXdebug(p)
	if err := dropStaleProjectImage(p, img); err != nil {
		ui.Warn("could not remove the old project image: %v", err)
	}
	announceStarted(p)
	if rebuild.noHooks {
		return nil
	}
	return runHooks(p, "post-start")
}

func announceStarted(p *config.Project) {
	if p.Webserver == "none" {
		ui.Success("Started project %s. Shell: lodev ssh", p.Name)
		return
	}
	urls := make([]string, len(p.WebDomains()))
	for i, d := range p.WebDomains() {
		urls[i] = "https://" + d
	}
	ui.Success("Started project %s. URL: %s", p.Name, strings.Join(urls, ", "))
}

// projectHome is the host folder mounted as the container user's home.
func projectHome(g *config.Global, p *config.Project) string {
	return filepath.Join(g.DataPath(), "home-"+p.Name)
}

func deleteProject(p *config.Project, dropDB, yes bool) error {
	reg, err := registry.Load()
	if err != nil {
		return err
	}
	// A copy (clone, worktree, cp -R) shares the name; never tear down the original.
	if err := reg.Conflict(p); err != nil {
		return fmt.Errorf("refusing to delete: %w", err)
	}
	// A project never started with the new lodev only has the legacy file.
	if _, err := os.Stat(composeFile(p)); err == nil {
		if err := projectCompose(p, "down"); err != nil {
			return err
		}
	}
	if err := removeProjectImage(p.Name); err != nil {
		return err
	}
	if err := hosts.Apply(p.Name, nil); err != nil {
		return err
	}
	if err := certs.Remove(p.Name); err != nil {
		return err
	}
	if err := certs.SyncTraefik(); err != nil {
		return err
	}
	delete(reg, p.Name)
	if err := reg.Save(); err != nil {
		return err
	}
	if g, err := config.LoadGlobal(); err == nil {
		h := projectHome(g, p)
		if _, err := os.Stat(h); err == nil {
			ui.Info("Kept %s (bash history, composer and npm caches)", h)
		}
	}
	if dropDB && p.DB() != "" && confirm(fmt.Sprintf("Drop database %s?", p.DBName()), yes) {
		if err := dbExec(p.DB(), fmt.Sprintf("DROP DATABASE IF EXISTS `%s`", p.DBName())); err != nil {
			return err
		}
		ui.Success("Dropped database %s", p.DBName())
	}
	return nil
}

var errNameWithAll = errors.New("cannot use a project name with --all")

// startFn is start, swappable in tests of the --all paths.
var startFn = start

// restartFn stops and starts p with its hooks; swapped in tests.
var restartFn = func(p *config.Project) error { return restartProject(p, startOpts{}) }

func restartProject(p *config.Project, o startOpts) error {
	// A stopped project has nothing to prepare for its stop.
	if !o.noHooks && containerRunning("lodev-"+p.Name+"-web") {
		if err := runHooks(p, "pre-stop"); err != nil {
			return fmt.Errorf("%w (lodev restart --no-hooks restarts anyway)", err)
		}
	}
	if err := projectCompose(p, "stop"); err != nil {
		return err
	}
	return startFn(p, o)
}

// forAll runs fn on every registry project; one failure does not stop the rest.
func forAll(fn func(*config.Project) error) error {
	reg, err := registry.Load()
	if err != nil {
		return err
	}
	var failed []string
	for _, name := range reg.Names() {
		ui.Info("Starting project %s", name)
		p, err := config.LoadProject(reg[name].Path)
		if errors.Is(err, fs.ErrNotExist) {
			ui.Warn("%s: %v (skipped)", name, err)
			continue
		}
		if err == nil {
			err = fn(p)
		}
		if err != nil {
			ui.Error("%s: %v", name, err)
			failed = append(failed, name)
		}
	}
	if len(failed) > 0 {
		return fmt.Errorf("failed: %s", strings.Join(failed, ", "))
	}
	return nil
}

// allThenServiceURLs runs fn on every project, then lists the shared services once.
func allThenServiceURLs(fn func(*config.Project) error) error {
	err := forAll(fn)
	if perr := printServiceURLs(); err == nil {
		err = perr
	}
	return err
}

func status(name string) string {
	out, _ := dockerOutput("ps", "-a", "--filter", "name=^lodev-"+name+"-web$", "--format", "{{.State}}")
	if out == "" {
		return "stopped"
	}
	return out
}

func init() {
	var name, typ, php, webserver, docroot string
	var noAsk bool
	createCmd := &cobra.Command{
		Use:     "create",
		Aliases: []string{"init"},
		Short:   "Create .lodev/config.yaml for the project in the current folder",
		Args:    cobra.NoArgs,
		RunE: func(c *cobra.Command, _ []string) error {
			root, err := os.Getwd()
			if err != nil {
				return err
			}
			if _, err := os.Stat(config.ProjectPath(root)); err == nil {
				return registerExisting(root)
			}
			p, err := newProjectConfig(root, name, typ, php, webserver, docroot)
			if err != nil {
				return err
			}
			if !noAsk && stdinTTY() {
				set := map[string]bool{}
				c.Flags().Visit(func(f *pflag.Flag) { set[f.Name] = true })
				if err := askProject(os.Stdin, os.Stdout, p, set); err != nil {
					return err
				}
			}
			if err := config.SaveProject(p); err != nil {
				return err
			}
			if err := scaffold(root, p.Webserver); err != nil {
				return err
			}
			if err := writeLodevGitignore(p); err != nil {
				return err
			}
			if err := registerProject(p); err != nil {
				return err
			}
			ui.Success("Created .lodev/config.yaml (%s, PHP %s, %s)\nRun: lodev start", p.Type, p.PHP, p.Webserver)
			return nil
		},
	}
	createCmd.Flags().StringVar(&name, "name", "", "project name (default: folder name)")
	createCmd.Flags().StringVar(&typ, "type", "", "laravel | wordpress | magento | php (default: detected)")
	createCmd.Flags().StringVar(&php, "php", "", "PHP version (default 8.4)")
	createCmd.Flags().StringVar(&webserver, "webserver", "", "nginx | apache | none (default nginx)")
	createCmd.Flags().StringVar(&docroot, "docroot", "", `document root relative to the project; "." for the project root (default: by type)`)
	createCmd.Flags().BoolVar(&noAsk, "no-ask", false, "do not prompt; use flags and detected values")

	var rebuild, rebuildBase, startAll, startNoHooks bool
	startCmd := &cobra.Command{
		Use:     "start [name]",
		Aliases: []string{"up"},
		Short:   "Start the project (current folder or [name]), or every project with --all (and the shared services if needed)",
		Args:    cobra.MaximumNArgs(1),
		RunE: func(_ *cobra.Command, args []string) error {
			if startAll {
				if len(args) > 0 {
					return errNameWithAll
				}
				return withLock(func() error {
					return allThenServiceURLs(func(p *config.Project) error { return startFn(p, startOpts{noHooks: startNoHooks}) })
				})
			}
			p, err := existingProject(args)
			if err != nil {
				return err
			}
			// --rebuild-base cleans the project image too: it is built on the base.
			opts := startOpts{project: rebuild || rebuildBase, base: rebuildBase, noHooks: startNoHooks}
			return withLock(func() error { return startFn(p, opts) })
		},
	}
	startCmd.Flags().BoolVar(&rebuild, "rebuild", false, "rebuild the project image without the build cache")
	startCmd.Flags().BoolVar(&rebuildBase, "rebuild-base", false, "also rebuild the shared PHP image(s) without the cache (fresh PHP packages; slow)")
	startCmd.Flags().BoolVar(&startAll, "all", false, "start every project lodev knows")
	startCmd.Flags().BoolVar(&startNoHooks, "no-hooks", false, "do not run the post-start hooks")
	startCmd.MarkFlagsMutuallyExclusive("all", "rebuild")
	startCmd.MarkFlagsMutuallyExclusive("all", "rebuild-base")

	var stopNoHooks bool
	stopCmd := &cobra.Command{
		Use:   "stop [name]",
		Short: "Stop the project container (current folder or [name])",
		Args:  cobra.MaximumNArgs(1),
		RunE: func(_ *cobra.Command, args []string) error {
			p, err := projectArg(args)
			if err != nil {
				return err
			}
			if !stopNoHooks && containerRunning("lodev-"+p.Name+"-web") {
				// Nothing is stopped yet: a failing pre-stop hook keeps the project running.
				if err := runHooks(p, "pre-stop"); err != nil {
					return fmt.Errorf("%w (lodev stop --no-hooks stops anyway)", err)
				}
			}
			return projectCompose(p, "stop")
		},
	}
	stopCmd.Flags().BoolVar(&stopNoHooks, "no-hooks", false, "do not run the pre-stop hooks")

	var restartAll bool
	var restartNoHooks bool
	restart := func(p *config.Project) error {
		if restartNoHooks {
			return restartProject(p, startOpts{noHooks: true})
		}
		return restartFn(p)
	}
	restartCmd := &cobra.Command{
		Use:   "restart [name]",
		Short: "Stop and start the project (current folder or [name]), or every project with --all",
		Args:  cobra.MaximumNArgs(1),
		RunE: func(_ *cobra.Command, args []string) error {
			if restartAll {
				if len(args) > 0 {
					return errNameWithAll
				}
				return withLock(func() error { return allThenServiceURLs(restart) })
			}
			p, err := existingProject(args)
			if err != nil {
				return err
			}
			return withLock(func() error { return restart(p) })
		},
	}
	restartCmd.Flags().BoolVar(&restartAll, "all", false, "restart every project lodev knows")
	restartCmd.Flags().BoolVar(&restartNoHooks, "no-hooks", false, "do not run the pre-stop and post-start hooks")

	var dropDB, yes bool
	removeCmd := &cobra.Command{
		Use:     "remove [name]",
		Aliases: []string{"down"},
		Short:   "Remove the project container, hosts entries and certificate (current folder or [name])",
		Args:    cobra.MaximumNArgs(1),
		RunE: func(_ *cobra.Command, args []string) error {
			p, err := projectArg(args)
			if err != nil {
				return err
			}
			return withLock(func() error { return deleteProject(p, dropDB, yes) })
		},
	}
	removeCmd.Flags().BoolVar(&dropDB, "db", false, "also drop the project database")
	removeCmd.Flags().BoolVar(&yes, "yes", false, "skip confirmation")

	listCmd := &cobra.Command{
		Use:     "list",
		Aliases: []string{"ps"},
		Short:   "List projects",
		Args:    cobra.NoArgs,
		RunE: func(c *cobra.Command, _ []string) error {
			reg, err := registry.Load()
			if err != nil {
				return err
			}
			var rows [][]string
			for _, name := range reg.Names() {
				e := reg[name]
				typ := "missing"
				if p, err := config.LoadProject(e.Path); err == nil {
					typ = p.Type
				}
				domains := strings.Join(e.Domains, "\n")
				if domains == "" {
					domains = "CLI"
				}
				rows = append(rows, []string{name, status(name), typ, domains, shortPath(e.Path)})
			}
			printTable(c.OutOrStdout(), []string{"NAME", "STATUS", "TYPE", "DOMAINS", "PATH"}, rows)
			return nil
		},
	}

	rootCmd.AddCommand(createCmd, startCmd, stopCmd, restartCmd, removeCmd, listCmd)
}

// warnWorkDirMove warns once, before the web container is recreated, when it ran the project in
// another folder: paths cached by the app and the IDE's path mapping still point there.
func warnWorkDirMove(p *config.Project) {
	cur, err := dockerOutput("inspect", "--format", "{{.Config.WorkingDir}}", "lodev-"+p.Name+"-web")
	if err != nil || cur == "" || cur == p.WorkDir() {
		return
	}
	ui.Warn("the project moves in the web container: %s → %s (working_dir)\n"+
		"flush caches that hold paths (Magento: bin/magento cache:flush) and update your IDE's path mapping", cur, p.WorkDir())
}

// registerExisting is lodev create in a folder that already has a .lodev/config.yaml (a cloned
// project, or one lodev remove dropped): it registers that config as it is.
func registerExisting(root string) error {
	reg, err := registry.Load()
	if err != nil {
		return err
	}
	if registered(reg, root) {
		return errors.New("already initialized (.lodev/config.yaml exists)")
	}
	p, err := config.LoadProject(root)
	if err != nil {
		return err
	}
	ui.Warn(".lodev/config.yaml already exists: registering the project with it as it is")
	if err := registerProject(p); err != nil {
		return err
	}
	ui.Success("Registered %s (%s, PHP %s, %s)\nRun: lodev start", p.Name, p.Type, p.PHP, p.Webserver)
	return nil
}
