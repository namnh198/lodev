func writeDotenv(t *testing.T, root, body string) {
	t.Helper()
	os.MkdirAll(filepath.Join(root, ".lodev"), 0o755)
	if err := os.WriteFile(filepath.Join(root, ".lodev", ".env"), []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
}

func TestProjectEnvPrecedence(t *testing.T) {
	p := confProject(t, "nginx")
	p.Environment = map[string]string{"A": "cfg", "B": "cfg"}
	writeDotenv(t, p.Root, "B=env\nC=env\n")
	got, err := projectEnv(p)
	if want := map[string]string{"A": "cfg", "B": "env", "C": "env"}; err != nil || !maps.Equal(got, want) {
		t.Fatalf("%v, %v", got, err)
	}
	if p.Environment["B"] != "cfg" {
		t.Error("projectEnv changed p.Environment")
	}
}

func TestProjectEnvMissingFile(t *testing.T) {
	p := confProject(t, "nginx")
	p.Environment = map[string]string{"A": "1"}
	got, err := projectEnv(p)
	if err != nil || !maps.Equal(got, p.Environment) {
		t.Fatalf("%v, %v", got, err)
	}
}

func TestProjectEnvErrors(t *testing.T) {
	p := confProject(t, "nginx")
	writeDotenv(t, p.Root, "A=1\nLODEV_UID=2\n")
	if _, err := projectEnv(p); err == nil || err.Error() != ".lodev/.env:2: environment: LODEV_UID is reserved for lodev" {
		t.Errorf("reserved: %v", err)
	}
	writeDotenv(t, p.Root, "nope\n")
	if _, err := projectEnv(p); err == nil || !strings.HasPrefix(err.Error(), ".lodev/.env: line 1: ") {
		t.Errorf("parse: %v", err)
	}
}

func TestWriteDaemons(t *testing.T) {
	p := confProject(t, "nginx")
	p.WebExtraDaemons = []config.Daemon{{Name: "vite", Command: "npm run dev"}}
	dir := filepath.Join(p.Root, ".lodev", "daemons")
	if err := writeDaemons(p); err != nil {
		t.Fatal(err)
	}
	fi, err := os.Stat(filepath.Join(dir, "vite.sh"))
	if err != nil || fi.Mode().Perm() != 0o755 {
		t.Fatalf("vite.sh: %v %v", fi, err)
	}
	if b, _ := os.ReadFile(filepath.Join(dir, "daemons.conf")); !strings.Contains(string(b), "[program:daemon-vite]") {
		t.Fatalf("daemons.conf: %q", b)
	}
	before, _ := os.Stat(dir)
	p.WebExtraDaemons = []config.Daemon{{Name: "queue", Command: "php artisan queue:work"}}
	if err := writeDaemons(p); err != nil {
		t.Fatal(err)
	}
	// A running container bind-mounts the folder: it must stay the same one.
	if after, _ := os.Stat(dir); !os.SameFile(before, after) {
		t.Fatal("daemons folder was replaced, not rewritten")
	}
	if _, err := os.Stat(filepath.Join(dir, "vite.sh")); !errors.Is(err, fs.ErrNotExist) {
		t.Fatalf("stale vite.sh kept: %v", err)
	}
	p.WebExtraDaemons = nil
	if err := writeDaemons(p); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(dir); !errors.Is(err, fs.ErrNotExist) {
		t.Fatalf("daemons folder not removed: %v", err)
	}
	if err := writeDaemons(p); err != nil {
		t.Fatalf("no folder, no daemons: %v", err)
	}
}

func TestWriteCrontab(t *testing.T) {
	p := confProject(t, "nginx")
	p.Type, p.Cron = "magento", true
	f := filepath.Join(p.Root, ".lodev", "crontab")
	if err := writeCrontab(p); err != nil {
		t.Fatal(err)
	}
	want := "# Generated by lodev on every lodev start from .lodev/config.yaml (cron, cron_jobs); do not edit.\n" +
		p.CronLines()[0] + "\n"
	if b, _ := os.ReadFile(f); string(b) != want {
		t.Fatalf("%q", b)
	}
	p.Cron = false
	if err := writeCrontab(p); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(f); !errors.Is(err, fs.ErrNotExist) {
		t.Fatalf("crontab not removed: %v", err)
	}
	if err := writeCrontab(p); err != nil {
		t.Fatalf("no file, cron off: %v", err)
	}
}
