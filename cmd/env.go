package cmd

import (
	"errors"
	"fmt"
	"io/fs"
	"maps"
	"os"
	"path/filepath"
	"strings"

	"lodev/internal/config"
	"lodev/internal/dotenv"
)

// dotenvPath is the project's local env file, managed by `lodev dotenv`.
func dotenvPath(p *config.Project) string { return filepath.Join(p.Root, ".lodev", ".env") }

// projectEnv is environment: from config.yaml overlaid with .lodev/.env (which wins).
func projectEnv(p *config.Project) (map[string]string, error) {
	env := maps.Clone(p.Environment)
	if env == nil {
		env = map[string]string{}
	}
	data, err := os.ReadFile(dotenvPath(p))
	if errors.Is(err, fs.ErrNotExist) {
		return env, nil
	}
	if err != nil {
		return nil, err
	}
	entries, err := dotenv.Parse(data)
	if err != nil {
		return nil, fmt.Errorf(".lodev/.env: %w", err)
	}
	for _, e := range entries {
		if err := config.CheckEnvKey(e.Key); err != nil {
			return nil, fmt.Errorf(".lodev/.env:%d: %w", e.Line, err)
		}
		env[e.Key] = e.Value
	}
	return env, nil
}

// writeCrontab writes .lodev/crontab while cron is on and removes it otherwise.
func writeCrontab(p *config.Project) error {
	f := filepath.Join(p.Root, ".lodev", "crontab")
	lines := p.CronLines()
	if len(lines) == 0 {
		if err := os.Remove(f); err != nil && !errors.Is(err, fs.ErrNotExist) {
			return err
		}
		return nil
	}
	s := "# Generated by lodev on every lodev start from .lodev/config.yaml (cron, cron_jobs); do not edit.\n" +
		strings.Join(lines, "\n") + "\n"
	if err := os.MkdirAll(filepath.Dir(f), 0o755); err != nil {
		return err
	}
	return os.WriteFile(f, []byte(s), 0o644)
}
