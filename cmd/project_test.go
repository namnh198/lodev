func TestWriteLodevGitignore(t *testing.T) {
	p := confProject(t, "nginx")
	want := "# Generated by lodev on every `lodev start`; do not edit.\n/lodev.compose-base.yml\n/lodev.compose-full.yml\n/web-build/\n/crontab\n/.env\n" +
		"# each <ws>-webserver.conf below is listed only while it carries the marker\n/nginx-webserver.conf\n/apache-webserver.conf\n/varnish.vcl\n"
	gi := filepath.Join(p.Root, ".lodev", ".gitignore")
	if err := writeLodevGitignore(p); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(gi); string(b) != want {
		t.Fatalf("%q", b)
	}
	writeConf(t, p, "mine\n")
	if err := writeLodevGitignore(p); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(gi); string(b) != strings.Replace(want, "/nginx-webserver.conf\n", "", 1) {
		t.Fatalf("%q", b)
	}
	os.WriteFile(varnishVCLFile(p), []byte("mine\n"), 0o644)
	if err := writeLodevGitignore(p); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(gi); strings.Contains(string(b), "/varnish.vcl") {
		t.Fatalf("user-managed VCL still ignored: %q", b)
	}
	if _, err := os.Stat(filepath.Join(p.Root, ".gitignore")); err == nil {
		t.Fatal("root .gitignore created")
	}
}

