func TestWriteVarnishVCL(t *testing.T) {
	p := confProject(t, "nginx")
	vcl := varnishVCLFile(p)
	if err := writeVarnishVCL(p); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(vcl); err == nil {
		t.Fatal("VCL written with Varnish off")
	}
	p.Varnish = true
	for _, before := range []string{"", templates.GeneratedMarker + "\nold\n"} {
		if before != "" {
			os.WriteFile(vcl, []byte(before), 0o644)
		}
		if err := writeVarnishVCL(p); err != nil {
			t.Fatal(err)
		}
		if b, _ := os.ReadFile(vcl); !strings.HasPrefix(string(b), templates.GeneratedMarker) || strings.Contains(string(b), "old\n") {
			t.Fatalf("from %q: %q", before, b)
		}
	}
	os.WriteFile(vcl, []byte("mine\n"), 0o644)
	if err := writeVarnishVCL(p); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(vcl); string(b) != "mine\n" {
		t.Fatalf("user VCL overwritten: %q", b)
	}
}

